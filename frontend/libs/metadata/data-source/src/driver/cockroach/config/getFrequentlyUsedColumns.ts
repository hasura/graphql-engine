import { FrequentlyUsedColumn } from '../../types';
import { PostgresTable } from '../../postgres/types';
import {
  createdAtColumn,
  uuidIdColumn,
} from '../../postgres/config/getFrequentlyUsedColumns';

/**
 * CockroachDB variant of the Postgres presets.
 *
 * `serial` isn't auto-increment: with the default `serial_normalization`, a
 * `SERIAL`/`BIGSERIAL` column is an `INT8 DEFAULT unique_rowid()`, whose values
 * are unique but large and not sequential (e.g. `1001234567890123777`). The
 * sequential id is an identity column instead, and the `unique_rowid()` one is
 * named for what it is. `INT` is `INT8` in CockroachDB.
 *
 * Triggers need CockroachDB v24.3+, and the Postgres `updated_at` trigger SQL
 * is adapted because:
 * - PL/pgSQL `record` variables are unimplemented, so `NEW` is set directly;
 * - `COMMENT ON TRIGGER` is not supported;
 * - v24.3 cannot `CREATE OR REPLACE` a function an active trigger uses, so the
 *   function is named per table rather than shared across a schema.
 */
export const getFrequentlyUsedColumns = (): FrequentlyUsedColumn[] => [
  {
    name: 'id',
    validFor: ['add'],
    type: 'int8 GENERATED BY DEFAULT AS IDENTITY',
    typeText: 'bigint (auto-increment, identity)',
    primary: true,
  },
  {
    name: 'id',
    validFor: ['add'],
    type: 'int8',
    typeText: 'bigint (unique_rowid, not sequential)',
    primary: true,
    default: 'unique_rowid()',
  },
  uuidIdColumn,
  createdAtColumn,
  {
    name: 'updated_at',
    validFor: ['add', 'modify'],
    type: 'timestamptz',
    typeText: 'timestamp',
    default: 'now()',
    defaultText: 'now() + trigger to set value on update',
    dependentSQLGenerator: (table, columnName) => {
      const { schema: schemaName, name: tableName } = table as PostgresTable;
      const functionName = `set_current_timestamp_${tableName}_${columnName}`;
      const triggerName = `set_${schemaName}_${tableName}_${columnName}`;
      const upSql = `
CREATE OR REPLACE FUNCTION "${schemaName}"."${functionName}"()
RETURNS TRIGGER AS $$
BEGIN
  NEW."${columnName}" := NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER "${triggerName}"
BEFORE UPDATE ON "${schemaName}"."${tableName}"
FOR EACH ROW
EXECUTE FUNCTION "${schemaName}"."${functionName}"();
`;

      const downSql = `DROP TRIGGER IF EXISTS "${triggerName}" ON "${schemaName}"."${tableName}";`;

      return {
        upSql,
        downSql,
      };
    },
  },
];
